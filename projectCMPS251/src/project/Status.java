package project;

/**
 * This enum represents the status of a visa application.
 * It can be pending, approved, or rejected.
 * 
 * @author Shaikha Aldosari 202303941
 * @version 0.1
 * @since 18/4/2026
 */
public enum Status {

    /**
     * Application is not processed yet
     */
    PENDING,

    /**
     * Application has been approved
     */
    APPROVED,

    /**
     * Application has been rejected
     */
    REJECTED
}
